// ── Overlay logic ──────────────────────────────────────────────

const overlay   = document.getElementById('exp-overlay');
const closeBtn  = document.getElementById('expClose');
const scrollEl  = document.getElementById('expScroll');
const tagEl     = document.getElementById('expTag');
const companyEl = document.getElementById('expCompany');
const roleEl    = document.getElementById('expRole');
const metaEl    = document.getElementById('expMeta');
const chaptersEl = document.getElementById('expChapters');

function buildImageSlot(src) {
  if (src) {
    return `<div class="exp-img-wrap"><img src="${src}" alt="" /></div>`;
  }
  return `
    <div class="exp-img-placeholder">
      <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1">
        <rect x="3" y="3" width="18" height="18" rx="2"/><circle cx="8.5" cy="8.5" r="1.5"/>
        <polyline points="21 15 16 10 5 21"/>
      </svg>
      <span>Photo coming soon</span>
    </div>`;
}

function buildImageGallery(images) {
  if (!images || images.length === 0) return '';

  const filled = images.filter(Boolean);
  const empty  = images.filter(s => !s);

  if (filled.length === 0) return ''; // no photos yet, show nothing

  if (filled.length === 1) {
    return `<div class="exp-img-wrap exp-img-single"><img src="${filled[0]}" alt="" /></div>`;
  }

  const items = filled.map(src =>
    `<div class="exp-gallery-item"><img src="${src}" alt="" /></div>`
  ).join('');
  return `<div class="exp-gallery exp-gallery-${Math.min(filled.length, 3)}">${items}</div>`;
}

function openExperience(id) {
  const exp = EXPERIENCES[id];
  if (!exp) return;

  tagEl.textContent      = '// Experience';
  companyEl.textContent  = exp.company;
  roleEl.textContent     = exp.role;
  metaEl.textContent     = `${exp.period}  ·  ${exp.location}`;

  chaptersEl.innerHTML = exp.chapters.map((ch, i) => `
    <div class="exp-chapter">
      <div class="exp-chapter-num">${String(i + 1).padStart(2, '0')}</div>
      <h3 class="exp-chapter-heading">${ch.heading}</h3>
      <div class="exp-chapter-text">${ch.text.split('\n\n').map(p => `<p>${p}</p>`).join('')}</div>
      ${'images' in ch ? buildImageGallery(ch.images) : buildImageSlot(ch.image)}
    </div>
  `).join('');

  scrollEl.scrollTop = 0;
  overlay.classList.add('open');
  overlay.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
}

function closeOverlay() {
  overlay.classList.remove('open');
  overlay.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
}

closeBtn.addEventListener('click', closeOverlay);
overlay.addEventListener('click', e => { if (e.target === overlay) closeOverlay(); });
document.addEventListener('keydown', e => { if (e.key === 'Escape') closeOverlay(); });

document.querySelectorAll('.tl-item[data-exp]').forEach(item => {
  item.addEventListener('click', () => {
    if (item.dataset.exp === 'daydayup') {
      window.location.href = 'experiences.html';
    } else if (item.dataset.exp === 'leonglee') {
      window.location.href = 'leonglee.html';
    } else {
      openExperience(item.dataset.exp);
    }
  });
});
